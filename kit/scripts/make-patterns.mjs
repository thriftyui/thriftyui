// Writes src/patterns.css, the pattern finishes -- zebra, leopard, tiger,
// funfetti, sky and the fish tank -- from the tiles in src/patterns/. Run
// from kit/: `node scripts/make-patterns.mjs`.
//
// The animal tiles are grown by reaction-diffusion: the leopard after
// Malheiros et al. 2020, the zebra by anisotropic Gray-Scott with a curving
// axis, the tiger as the zebra, its stripes thinner and broken, on orange.
// Funfetti, sky and the fish tank's layers are drawn. Each tile is drawn
// at its own size, a pixel to a CSS pixel (zebra, tiger, funfetti and sky
// 384px, leopard 388px), the same in light and dark, and repeats without
// seams. They go into the stylesheet as data URLs, so the file works
// wherever it is imported -- through Tailwind's @import or a bundler's --
// with no image paths to resolve. The words on a pattern are the theme's
// own text.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'

const at = (path) => new URL(path, import.meta.url)
const rule = (selectors, body) => `${selectors.join(',\n')} {\n${body}\n}\n`
const tile = (name) => `url("data:image/png;base64,${readFileSync(at(`../src/patterns/${name}.png`)).toString('base64')}")`

const TILES = ['zebra', 'leopard', 'tiger', 'funfetti', 'sky']
const ALL = [...TILES, 'fishtank']
const VEIL = '  --veil: color-mix(in srgb, var(--neutral-1) 70%, transparent);'
/** A finish's rules: the veil over its layers, on the root and again on
 *  any part set light or dark, so it takes that part's step 1. */
const worn = (name, layers) =>
  rule([`[data-finish="${name}"]`, `[data-finish="${name}"] .light`], `${VEIL}\n  --finish: linear-gradient(var(--veil), var(--veil)), ${layers};`) +
  rule([`.dark[data-finish="${name}"]`, `[data-finish="${name}"] .dark`], `${VEIL}\n  --finish: linear-gradient(var(--veil), var(--veil)), ${layers};`)

const css = `/* Generated by scripts/make-patterns.mjs -- run it again rather than
   editing this file. The pattern finishes, zebra, leopard, tiger,
   funfetti, sky and the fish tank: where the tiles come from, the script;
   how a finish is worn, theme.css. Imported after theme.css, so a pattern
   on the root wins over its "none". */
/* A veil of the bar's own ground, the neutral's step 1, over the tile, so
   the bar's words read as on a plain bar. 70% in light and dark, and on
   a patterned bar the neutral's
   step 11 is its step 12, so grey words and icons turn its darkest: step
   12 then stays at least 8.01:1 in light and 6.03:1 in dark on the veiled
   tile at every one of its pixels (tiger 8.01:1 in light, funfetti 6.03:1
   in dark the least; the fish tank's brightest, a bubble over its yellow
   fish, 6.44:1), over all six neutrals, by WCAG's formula over
   @radix-ui/colors 3.0.0's values. The kit's colour classes read the steps
   directly (theme.css, @theme inline), so setting the step on the bar is
   enough. What is lost: a grey word no longer darkens on hover. */
:is(${ALL.map((n) => `[data-finish="${n}"]`).join(', ')}) .finish {
  --neutral-11: var(--neutral-12);
}
${TILES.map((name) => rule([`[data-finish="${name}"]`], `  --tile: ${tile(name)};`) + worn(name, 'var(--tile)')).join('')}
/* The fish tank: water, and over it three see-through layers -- far fish,
   small and dim; near fish; bubbles -- each a tile that repeats. Still, it
   is a picture of a tank. While the pointer is over a part wearing it,
   the layers move: each by its own tile's width (or height, the bubbles)
   in the same time, so the nearer fish move faster than the far ones and
   the tank looks deep, and the bubbles rise. Started by the person, not by
   the page, and only background positions move. With data-finish-motion=
   "loop" beside data-finish on the root, it swims all the time instead:
   then the app gives its people a way to stop it, as moving content that
   starts by itself and lasts more than five seconds must have (WCAG 2.2,
   2.2.2 Pause, Stop, Hide) -- a Loop switch they can turn off. Either way
   it holds still where the system asks for less motion
   (prefers-reduced-motion). */
[data-finish="fishtank"] {
  --tank-far: ${tile('fishtank-far')};
  --tank-near: ${tile('fishtank-near')};
  --tank-bubbles: ${tile('fishtank-bubbles')};
  --tank-water: linear-gradient(#1b7f9b, #0f5872);
}
${worn('fishtank', 'var(--tank-bubbles), var(--tank-near), var(--tank-far), var(--tank-water)')}@keyframes finish-swim {
  to {
    background-position: 0 0, 0 -64px, 384px 0, 256px 0, 0 0;
  }
}
@media (prefers-reduced-motion: no-preference) {
  [data-finish="fishtank"] .finish:hover,
  [data-finish="fishtank"][data-finish-motion="loop"] .finish {
    animation: finish-swim 12s linear infinite;
  }
}
`
writeFileSync(at('../src/patterns.css'), css)
console.log('patterns.css', `${(css.length / 1024).toFixed(1)} KB`)

// One file a finish, src/finishes/<name>.css: the same rules as patterns.css
// for that finish alone, so an app wearing one loads one, not all six
// (thriftyui/finishes/<name>.css, imported after theme.css as patterns.css is).
const greys = (name) => `[data-finish="${name}"] .finish {\n  --neutral-11: var(--neutral-12);\n}\n`
const fishtank = css.slice(css.indexOf('/* The fish tank:'))
mkdirSync(at('../src/finishes/'), { recursive: true })
for (const name of ALL) {
  const head = `/* Generated by scripts/make-patterns.mjs -- run it again rather than
   editing this file. The ${name === 'fishtank' ? 'fish tank' : name} finish alone, as patterns.css has
   it with the others: why its grey words turn to step 12, and how a finish
   is worn, there and in theme.css. Imported after theme.css. */\n`
  const body = name === 'fishtank' ? fishtank : rule([`[data-finish="${name}"]`], `  --tile: ${tile(name)};`) + worn(name, 'var(--tile)')
  const file = head + greys(name) + body
  writeFileSync(at(`../src/finishes/${name}.css`), file)
  console.log(`finishes/${name}.css`, `${(file.length / 1024).toFixed(1)} KB`)
}
